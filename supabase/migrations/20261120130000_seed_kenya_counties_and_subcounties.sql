create table if not exists public.kenya_counties (county_code integer primary key,name text not null unique,sort_order integer not null,source text not null default 'KNBS 2019 Kenya Population and Housing Census, Volume II');
create table if not exists public.kenya_subcounties (subcounty_code text primary key,county_code integer not null references public.kenya_counties(county_code) on delete restrict,name text not null,unique(county_code,name));
create index if not exists kenya_subcounties_county_idx on public.kenya_subcounties(county_code,name);
alter table public.kenya_counties enable row level security;
alter table public.kenya_subcounties enable row level security;
revoke all on public.kenya_counties,public.kenya_subcounties from public;
grant select on public.kenya_counties,public.kenya_subcounties to anon,authenticated;
grant all on public.kenya_counties,public.kenya_subcounties to service_role;
drop policy if exists "Kenya counties are publicly readable" on public.kenya_counties;
create policy "Kenya counties are publicly readable" on public.kenya_counties for select to anon,authenticated using(true);
drop policy if exists "Kenya subcounties are publicly readable" on public.kenya_subcounties;
create policy "Kenya subcounties are publicly readable" on public.kenya_subcounties for select to anon,authenticated using(true);
