insert into public.destinations(name,city,county,country,country_code,active,destination_type,population_2019,sort_order)
select u.name,u.name,u.county_name,'Kenya','KE',true,'urban_centre',u.population_2019,u.population_rank
from public.kenya_urban_centres u
where not exists (
 select 1 from public.destinations d
 where lower(d.city)=lower(u.name) and lower(coalesce(d.county,''))=lower(u.county_name) and lower(d.country)='kenya'
);
update public.destinations d set destination_type='urban_centre',population_2019=u.population_2019,sort_order=u.population_rank
from public.kenya_urban_centres u
where lower(d.city)=lower(u.name) and lower(coalesce(d.county,''))=lower(u.county_name);
