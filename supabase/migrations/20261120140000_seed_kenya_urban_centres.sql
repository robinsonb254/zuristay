alter table public.destinations add column if not exists destination_type text not null default 'urban_centre';
alter table public.destinations add column if not exists population_2019 integer;
alter table public.destinations add column if not exists sort_order integer;
create table if not exists public.kenya_urban_centres (
  id bigint generated always as identity primary key,
  name text not null,
  county_name text not null,
  population_2019 integer not null check(population_2019 >= 0),
  population_rank integer not null,
  source text not null default 'KNBS 2019 Kenya Population and Housing Census, Volume II, Table 2.5',
  unique(name,county_name)
);
alter table public.kenya_urban_centres enable row level security;
revoke all on public.kenya_urban_centres from public;
grant select on public.kenya_urban_centres to anon,authenticated;
grant all on public.kenya_urban_centres to service_role;
drop policy if exists "Kenya urban centres are publicly readable" on public.kenya_urban_centres;
create policy "Kenya urban centres are publicly readable" on public.kenya_urban_centres for select to anon,authenticated using(true);
